// Builds the dashboard page from the dataset (data.mjs) and stores it.
// The page is one self-contained HTML file: the styles, the dataset and view.mjs (which wrote the first view
// here and redraws it in the browser when a filter changes) are all inlined, so it opens straight from S3 or
// from a download, with nothing else to fetch.
import { readFileSync } from 'node:fs';
import { decode, select, renderSales, renderInventory, DEFAULT_STATE, esc, fmtDate, fmtTime } from './view.mjs';

const VIEW = readFileSync(new URL('./view.mjs', import.meta.url), 'utf8');
const STYLES = readFileSync(new URL('./styles.css', import.meta.url), 'utf8');
// Both go inside <script>/<style> elements, which these sequences would end or garble.
if (/<\/(script|style)|<!--/i.test(VIEW + STYLES)) throw new Error('view.mjs and styles.css must not contain "</script", "</style" or "<!--".');

export const LATEST_KEY = 'reports/dashboard/latest.html';

// The same key layout as the CSV reports in backend/src/services/reports.js: reports/<type>/YYYY/MM/DD/<type>-<SGT time>.
const sgDate = (ts) => new Date(ts).toLocaleString('sv-SE', { timeZone: 'Asia/Singapore' }).replace(' ', 'T');
export function dashboardKey(ts) {
  const stamp = sgDate(ts).replace(/[:]/g, '').slice(0, 17);
  const [y, m, d] = stamp.slice(0, 10).split('-');
  return `reports/dashboard/${y}/${m}/${d}/dashboard-${stamp}.html`;
}

export function renderPage(data) {
  const ds = decode(data);
  const generated = `${fmtDate(data.generatedAt)}, ${fmtTime(data.generatedAt)} SGT`;
  // In a JSON script element only "<" could end it early; < parses back to the same string.
  const json = JSON.stringify(data).replace(/</g, '\\u003c');
  return `<!doctype html>
<html lang="en-SG">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Sales dashboard · Kool Kaya Kitchen · ${esc(generated)}</title>
<style>
${STYLES}
</style>
<script>document.documentElement.classList.add('js')</script>
</head>
<body>
<div class="band"><strong>Kool Kaya Kitchen</strong><span>Generated ${esc(generated)}</span></div>
<div class="wrap">
<header class="head">
<h1>Sales dashboard</h1>
<p>Paid orders from the shop database, in Singapore time (SGT). Amounts in SGD unless another currency is shown.</p>
<div class="sheets" role="tablist" aria-label="Sheets"><button type="button" role="tab" id="tab-sales" aria-controls="sales" aria-selected="true" data-sheet="sales">Sales</button><button type="button" role="tab" id="tab-inventory" aria-controls="inventory" aria-selected="false" tabindex="-1" data-sheet="inventory">Inventory</button></div>
</header>
<main>
<section id="sales" class="sheet active" role="tabpanel" aria-labelledby="tab-sales">
${renderSales(ds, select(ds, DEFAULT_STATE))}
</section>
<section id="inventory" class="sheet" role="tabpanel" aria-labelledby="tab-inventory">
${renderInventory(ds)}
</section>
</main>
<footer class="foot">
<dl>
<dt>Revenue</dt><dd>What customers paid for paid orders: item prices after discounts, plus shipping, converted to SGD at each order's rate.</dd>
<dt>Item sales</dt><dd>Item price × quantity, before order discounts and shipping.</dd>
<dt>Customers</dt><dd>Distinct buyers.</dd>
<dt>Days of cover</dt><dd>Stock ÷ average daily units sold over the last 30 days.</dd>
</dl>
<p>Refunded and cancelled orders are left out, and so are orders already moved to the archive. Generated by the report-dashboard Lambda; this file holds no customer names, emails or addresses.</p>
</footer>
</div>
<script type="application/json" id="kk-data">${json}</script>
<script type="module">
${VIEW}
boot(document);
</script>
</body>
</html>
`;
}

// put(key, html, { cacheControl }) stores one file and returns where it went: once under a dated key, once as latest.
export async function publish(data, put) {
  const html = renderPage(data);
  const location = await put(dashboardKey(data.generatedAt), html);
  const latest = await put(LATEST_KEY, html, { cacheControl: 'no-cache' });
  return { location, latest, orders: data.orders.length, bytes: Buffer.byteLength(html) };
}
